#!/usr/bin/env node
// Generates service/ca.js from the ISRG roots in certs/ (downloaded from
// letsencrypt.org/certificates). Run it again when Let's Encrypt publishes new roots.
//   node webos/tlsproxy/gen-ca.js           writes service/ca.js
//   node webos/tlsproxy/gen-ca.js --check   exits 1 if service/ca.js does not match certs/
// The check runs in pnpm test (webos/tests/tlsproxy/service-files.test.js) and before packaging.
'use strict';

const fs = require('fs');
const path = require('path');
const { X509Certificate } = require('crypto');

const CERTS_DIR = path.join(__dirname, 'certs');
const CA_FILE = path.join(__dirname, 'service', 'ca.js');

const render = () => {
    const roots = fs.readdirSync(CERTS_DIR)
        .filter((file) => file.endsWith('.pem'))
        .map((file) => {
            const pem = fs.readFileSync(path.join(CERTS_DIR, file), 'utf8');
            const cert = new X509Certificate(pem);
            const name = cert.subject.split('\n').find((line) => line.startsWith('CN=')).slice(3);
            const body = pem.split('\n').filter((line) => line.trim()).map((line) => `${line}\\n`).join('');
            return { name, fingerprint: cert.fingerprint256, body };
        })
        .sort((a, b) => (a.name < b.name ? -1 : 1));
    return [
        '// Generated by gen-ca.js from certs/*.pem. Do not edit by hand.',
        '\'use strict\';',
        'module.exports = [',
        ...roots.flatMap(({ name, fingerprint, body }) => [
            `    // ${name}, SHA-256 ${fingerprint}`,
            `    '${body}',`,
        ]),
        '];',
        '',
    ].join('\n');
};

if (require.main === module) {
    const expected = render();
    if (process.argv.includes('--check')) {
        if (fs.readFileSync(CA_FILE, 'utf8') !== expected) {
            console.error('error: webos/tlsproxy/service/ca.js does not match certs/, run node webos/tlsproxy/gen-ca.js');
            process.exit(1);
        }
    } else {
        fs.writeFileSync(CA_FILE, expected);
    }
    // eslint-disable-next-line no-console
    console.log(`service/ca.js: ${(expected.match(/BEGIN CERTIFICATE/g) || []).length} roots`);
}

module.exports = { render, CA_FILE };
